import { expect, launch, openRailSection, stubOpenExternal, test, userDataDir } from './harness'

const weekday = ![0, 6].includes(new Date().getDay())
const env = { INTERSECT_E2E_MEETINGS: '1' }

test('one shared calendar fetch shows Dashboard meetings and durable time proposals', async () => {
  test.skip(!weekday, 'The Time Tracking board has Monday–Friday columns')
  const { app, win, errors } = await launch(userDataDir(), { env })
  const opened = await stubOpenExternal(app)
  await expect(win.locator('.ix-dash-meetings__row')).toHaveCount(3)
  await expect(win.locator('.ix-dash-meetings__row').first()).toContainText('Synthetic planning meeting')
  await expect(win.locator('.ix-dash-meetings__row').first()).toContainText('09:00')
  await expect(win.locator('.ix-dash-meetings__row button', { hasText: 'Join' })).toHaveCount(1)
  await win.locator('.ix-dash-meetings__row button', { hasText: 'Join' }).click()
  await expect.poll(opened).toEqual(['https://teams.microsoft.com/l/meetup-join/synthetic'])
  await win.locator('.ix-dash-meetings button', { hasText: 'Refresh' }).click()
  await expect(win.locator('.ix-dash-meetings__row')).toHaveCount(3)

  await openRailSection(win, 'Time Tracking', '.ix-tt')
  await expect(win.locator('.ix-tt__day--today .ix-tt-proposal')).toHaveCount(3)
  await expect(win.locator('.ix-tt__total')).toHaveText('0m total')
  await win.locator('[data-proposal-id="synthetic-plan"] button', { hasText: 'Accept' }).click()
  await expect(win.locator('[data-proposal-id="synthetic-plan"]')).toHaveCount(0)
  await expect(win.locator('.ix-tt__day--today .ix-tt-card')).toHaveCount(1)
  await win.locator('[data-proposal-id="synthetic-review"] button', { hasText: 'Decline' }).click()
  await expect(win.locator('[data-proposal-id="synthetic-review"]')).toHaveCount(0)
  await win.locator('.ix-tt__day--today button', { hasText: 'Accept all' }).click()
  await expect(win.locator('.ix-tt__day--today .ix-tt-proposal')).toHaveCount(0)
  await expect(win.locator('.ix-tt__day--today .ix-tt-card')).toHaveCount(2)
  await expect(win.locator('.ix-tt__total')).toHaveText('45m total')

  await openRailSection(win, 'Dashboard', '.ix-dash')
  await win.locator('.ix-dash-meetings button', { hasText: 'Refresh' }).click()
  await openRailSection(win, 'Time Tracking', '.ix-tt')
  await expect(win.locator('.ix-tt__day--today .ix-tt-proposal')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('Settings rule edits route an untouched meeting proposal', async () => {
  test.skip(!weekday, 'The Time Tracking board has Monday–Friday columns')
  const { win, errors } = await launch(userDataDir(), { env })
  await expect(win.locator('.ix-dash-meetings__row')).toHaveCount(3)
  await openRailSection(win, 'Settings', '.ix-settings')
  await win.locator('.ix-settings__nav-btn', { hasText: 'Time Tracking' }).click()
  await win.getByRole('button', { name: 'Add rule' }).click()
  await win.getByLabel('Pattern 1').fill('review')
  await win.getByLabel('Issue key 1').fill('APP-12')
  await win.getByRole('button', { name: 'Save routing' }).click()
  await openRailSection(win, 'Dashboard', '.ix-dash')
  await win.locator('.ix-dash-meetings button', { hasText: 'Refresh' }).click()
  await openRailSection(win, 'Time Tracking', '.ix-tt')
  await expect(win.locator('[data-proposal-id="synthetic-review"]')).toContainText('APP-12')
  expect(errors).toEqual([])
})
