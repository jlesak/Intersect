import { expect, launch, openRailSection, test, userDataDir } from './harness'
import type { Page } from '@playwright/test'

const pad = (n: number) => String(n).padStart(2, '0')
const dayFromToday = (offset: number): string => {
  const now = new Date()
  const date = new Date(now.getFullYear(), now.getMonth(), now.getDate() + offset)
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
}
const rows = (win: Page) => win.locator('.ix-todo > .ix-todo__list > .ix-todo-item')
async function openTodo(win: Page) { await openRailSection(win, 'TODO', '.ix-todo') }
async function project(win: Page, name: string) {
  await win.getByTitle('New TODO project').click()
  await win.getByRole('textbox', { name: 'Project name' }).fill(name)
  await win.getByRole('textbox', { name: 'Project name' }).press('Enter')
  await expect(win.locator('.ix-todo-nav__item', { hasText: name })).toBeVisible()
}
async function add(win: Page, text: string) {
  await win.getByPlaceholder('Add a task… (Enter)').fill(text)
  await win.getByPlaceholder('Add a task… (Enter)').press('Enter')
  await expect(rows(win).filter({ hasText: text })).toHaveCount(1)
}

test('renames projects and tags in the desktop app', async () => {
  const { win } = await launch(userDataDir())
  await openTodo(win)
  await project(win, 'Initial project')
  await win.getByTitle('Rename Initial project').click()
  await win.getByRole('textbox', { name: 'Rename project' }).fill('Renamed project')
  await win.getByRole('textbox', { name: 'Rename project' }).press('Enter')
  await expect(win.locator('.ix-todo-nav__item', { hasText: 'Renamed project' })).toBeVisible()
  await win.getByRole('textbox', { name: 'New tag name' }).fill('Initial tag')
  await win.getByRole('button', { name: 'Add tag' }).click()
  await win.getByTitle('Rename tag Initial tag').click()
  await win.getByRole('textbox', { name: 'Rename tag' }).fill('Renamed tag')
  await win.getByRole('textbox', { name: 'Rename tag' }).press('Enter')
  await expect(win.getByTitle('Rename tag Renamed tag')).toBeVisible()
})

test('projects, tags, saved filters, and crowded calendar survive restart', async () => {
  const profile = userDataDir()
  const first = await launch(profile)
  await first.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(940, 600))
  await openTodo(first.win)
  await project(first.win, 'Build')
  await project(first.win, 'Review')
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Build' }).click()
  await first.win.getByRole('textbox', { name: 'New tag name' }).fill('Quick')
  await first.win.getByRole('button', { name: 'Add tag' }).click()
  await expect(first.win.getByText('Quick').first()).toBeVisible()
  await first.win.getByRole('textbox', { name: 'New tag name' }).fill('Home')
  await first.win.getByRole('button', { name: 'Add tag' }).click()
  await first.win.getByRole('combobox', { name: 'New task priority' }).selectOption('1')
  await first.win.getByRole('combobox', { name: 'New task size' }).selectOption('S')
  await first.win.locator('.ix-todo__add-options label', { hasText: 'Quick' })
    .locator('input').check()
  await first.win.locator('.ix-todo__add-options label', { hasText: 'Home' })
    .locator('input').check()
  await first.win.getByTitle('Add due date').click()
  await first.win.locator('.ix-todo__date').fill(dayFromToday(0))
  await first.win.getByLabel('New task due time').fill('09:30')
  await add(first.win, 'urgent one')
  await expect(rows(first.win).first().locator('.ix-todo-item__size')).toHaveText('S')
  await expect(rows(first.win).first().locator('.ix-todo-item__prio')).toHaveText('P1')
  await expect(rows(first.win).first().locator('.ix-todo-item__tag')).toHaveCount(2)
  await expect(rows(first.win).first().locator('.ix-todo-item__meta')).toContainText('Quick')
  await expect(rows(first.win).first().locator('.ix-todo-item__meta')).toContainText('Home')
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Review' }).click()
  await add(first.win, 'review one')
  await rows(first.win).first().getByTitle('Edit').click()
  await first.win.getByRole('combobox', { name: 'TODO project' }).selectOption({ label: 'Build' })
  await first.win.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(rows(first.win)).toHaveCount(0)
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Build' }).click()
  await expect(rows(first.win)).toHaveCount(2)

  await first.win.getByRole('button', { name: 'New filter' }).click()
  await first.win.getByRole('textbox', { name: 'Filter name' }).fill('Urgent small')
  await first.win.locator('.ix-todo-filter-editor__group').filter({ hasText: 'Projects' })
    .getByLabel('Build').check()
  await first.win.locator('.ix-todo-filter-editor__group').filter({ hasText: 'Priority' })
    .getByLabel('P1').check()
  await first.win.getByRole('combobox', { name: 'Filter size', exact: true }).selectOption('S')
  await first.win.getByRole('combobox', { name: 'Filter size mode' }).selectOption('atMost')
  await first.win.getByRole('button', { name: 'Save filter' }).click()
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Urgent small' }).click()
  await expect(rows(first.win).locator('.ix-todo-item__text')).toHaveText(['urgent one'])

  await first.win.locator('.ix-todo-nav__item', { hasText: 'Upcoming' }).click()
  await expect(first.win.locator('.ix-todo-calendar__day button', { hasText: 'urgent one' })).toBeVisible()
  await expect(first.win.locator('.ix-todo-calendar__day button', { hasText: 'urgent one' }))
    .toContainText('09:30')
  await first.win.getByRole('button', { name: 'Next month' }).click()
  await expect(first.win.locator('.ix-todo-calendar__day button', { hasText: 'urgent one' })).toHaveCount(0)
  await first.win.getByRole('button', { name: 'Previous month' }).click()
  await expect(first.win.locator('.ix-todo-calendar__day button', { hasText: 'urgent one' })).toBeVisible()
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Inbox' }).click()
  for (let i = 0; i < 4; i++) await add(first.win, `crowded ${i}`)
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Upcoming' }).click()
  await first.win.getByRole('button', { name: /Show all/ }).click()
  await expect(first.win.locator('.ix-todo-calendar__expanded-list button')).toHaveCount(6)
  await first.win.locator('.ix-todo-calendar__expanded-list button', { hasText: 'crowded 3' }).click()
  await expect(first.win.locator('.ix-todo-item--editing')).toBeVisible()
  await first.app.close()

  const second = await launch(profile)
  await openTodo(second.win)
  await second.win.locator('.ix-todo-nav__item', { hasText: 'Urgent small' }).click()
  await expect(rows(second.win).locator('.ix-todo-item__text')).toHaveText(['urgent one'])
  await second.win.locator('.ix-todo-nav__item', { hasText: 'Build' }).click()
  await expect(rows(second.win)).toHaveCount(2)
  await rows(second.win).filter({ hasText: 'urgent one' }).getByTitle('Edit').click()
  await expect(second.win.locator('.ix-todo-item--editing input[type="time"]')).toHaveValue('09:30')
  await expect(second.win.locator('.ix-todo-item__tags input:checked')).toHaveCount(2)
})

test('recurrence completion is durable and a deleted filter reference is explicit', async () => {
  const profile = userDataDir()
  const first = await launch(profile)
  await openTodo(first.win)
  await project(first.win, 'Routine')
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Routine' }).click()
  await first.win.getByRole('combobox', { name: 'New task repeat mode' }).selectOption('fixed')
  await first.win.getByRole('combobox', { name: 'New task repeat unit' }).selectOption('day')
  await add(first.win, 'fixed routine')
  await rows(first.win).first().locator('.ix-todo-item__check').click()
  await expect(rows(first.win).first().locator('.ix-todo-item__due')).toHaveText(/tomorrow/)
  await rows(first.win).first().getByTitle('Edit').click()
  await expect(first.win.locator('.ix-todo-item__history')).toContainText(dayFromToday(0))
  await first.win.getByRole('button', { name: 'Cancel' }).click()
  await first.win.getByRole('combobox', { name: 'New task repeat mode' })
    .selectOption('after_completion')
  await first.win.getByRole('combobox', { name: 'New task repeat unit' }).selectOption('week')
  await add(first.win, 'relative routine')
  await rows(first.win).filter({ hasText: 'relative routine' }).locator('.ix-todo-item__check').click()
  await rows(first.win).filter({ hasText: 'relative routine' }).getByTitle('Edit').click()
  await expect(first.win.locator('.ix-todo-item--editing input[type="date"]'))
    .toHaveValue(dayFromToday(7))
  await expect(first.win.locator('.ix-todo-item__history')).toContainText(dayFromToday(0))
  await first.win.getByRole('button', { name: 'Cancel' }).click()

  await first.win.getByRole('button', { name: 'New filter' }).click()
  await first.win.getByRole('textbox', { name: 'Filter name' }).fill('Routine only')
  await first.win.locator('.ix-todo-filter-editor__group').filter({ hasText: 'Projects' })
    .getByLabel('Routine').check()
  await first.win.getByRole('button', { name: 'Save filter' }).click()
  await first.win.getByTitle('Delete Routine').click()
  await first.win.locator('.ix-todo-nav__item', { hasText: 'Routine only' }).click()
  await expect(first.win.getByRole('alert')).toContainText('Filtr odkazuje na smazaný projekt')
  await expect(rows(first.win)).toHaveCount(0)
  await first.app.close()

  const second = await launch(profile)
  await openTodo(second.win)
  await second.win.locator('.ix-todo-nav__item', { hasText: 'Routine only' }).click()
  await expect(second.win.getByRole('alert')).toContainText('Filtr odkazuje na smazaný projekt')
  await second.win.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(second.win.getByText(/Deleted project/)).toBeVisible()
  await second.win.getByRole('button', { name: 'Cancel' }).click()
  await second.win.locator('.ix-todo-nav__item', { hasText: 'Inbox' }).click()
  await rows(second.win).filter({ hasText: 'fixed routine' }).getByTitle('Edit').click()
  await expect(second.win.locator('.ix-todo-item__history')).toContainText(dayFromToday(0))
})

test('a changed repeat interval counts from the due day the task showed', async () => {
  const { win } = await launch(userDataDir())
  await openTodo(win)
  await win.getByRole('combobox', { name: 'New task repeat mode' }).selectOption('fixed')
  await win.getByRole('combobox', { name: 'New task repeat unit' }).selectOption('day')
  await add(win, 'edited rhythm')
  const row = rows(win).filter({ hasText: 'edited rhythm' })
  await row.locator('.ix-todo-item__check').click()
  await expect(row.locator('.ix-todo-item__due')).toHaveText(/tomorrow/)
  await row.getByTitle('Edit').click()
  await win.getByRole('spinbutton', { name: 'Repeat interval' }).fill('3')
  await win.getByRole('button', { name: 'Save' }).click()
  await expect(win.locator('.ix-todo-item--editing')).toHaveCount(0)
  await row.locator('.ix-todo-item__check').click()
  await row.getByTitle('Edit').click()
  // Every 3 days from tomorrow's occurrence, not from the day the task was created.
  await expect(win.locator('.ix-todo-item--editing input[type="date"]'))
    .toHaveValue(dayFromToday(4))
})

test('Dashboard task opens its project even from an excluding filter', async () => {
  const { win } = await launch(userDataDir())
  await openTodo(win)
  await project(win, 'Build')
  await win.locator('.ix-todo-nav__item', { hasText: 'Build' }).click()
  await win.getByTitle('Add due date').click()
  await win.locator('.ix-todo__date').fill(dayFromToday(-1))
  await add(win, 'overdue project task')
  await win.locator('.ix-todo-nav__item', { hasText: 'Today' }).click()
  await expect(rows(win).filter({ hasText: 'overdue project task' })).toHaveCount(1)
  await win.locator('.ix-todo-nav__item', { hasText: 'Build' }).click()
  await win.getByRole('button', { name: 'New filter' }).click()
  await win.getByRole('textbox', { name: 'Filter name' }).fill('Inbox only')
  await win.locator('.ix-todo-filter-editor__group').filter({ hasText: 'Projects' })
    .getByLabel('Inbox').check()
  await win.getByRole('button', { name: 'Save filter' }).click()
  await win.locator('.ix-todo-nav__item', { hasText: 'Inbox only' }).click()
  await expect(rows(win)).toHaveCount(0)
  await win.locator('.ix-rail__btn', { hasText: 'Dashboard' }).click()
  await win.locator('.ix-dash-row--todo', { hasText: 'overdue project task' }).click()
  await expect(win.locator('.ix-todo__title')).toContainText('Build')
  await expect(rows(win).filter({ hasText: 'overdue project task' }))
    .toHaveClass(/ix-todo-item--focused/)
})
