import { execFileSync } from 'node:child_process'
import { rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { addWorkspace, expect, launch, openRailSection, stubFolderPick, stubQuitConfirm, tempDir, test, unconfiguredAdo, userDataDir } from './harness'

function git(dir: string, ...args: string[]): string {
  return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim()
}

test('project Git chip refreshes external changes and drives commit and new branch at minimum size', async () => {
  const root = tempDir('intersect-project-git-')
  const repo = join(root, 'repo')
  const origin = join(root, 'origin.git')
  git(root, 'init', '--bare', origin)
  git(root, 'init', '-b', 'main', repo)
  git(repo, 'config', 'user.name', 'Test')
  git(repo, 'config', 'user.email', 'test@example.com')
  writeFileSync(join(repo, 'tracked'), 'one\n')
  git(repo, 'add', '-A')
  git(repo, 'commit', '-m', 'initial')
  git(repo, 'remote', 'add', 'origin', origin)
  git(repo, 'push', '-u', 'origin', 'main')

  const profile = userDataDir()
  const { app, win, errors } = await launch(profile, { env: unconfiguredAdo() })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(940, 600))
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize())).toEqual([940, 600])
  const contentSize = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getContentSize())
  await expect.poll(() => win.evaluate(() => [innerWidth, innerHeight])).toEqual(contentSize)

  await openRailSection(win, 'Settings', '.ix-settings')
  await stubFolderPick(app, repo)
  await win.getByRole('button', { name: 'Nový projekt (vybrat složku)' }).click()
  await expect(win.locator('.ix-proj')).toHaveCount(1)
  await win.locator('.ix-rail__btn--project').click()
  const chip = win.locator('.ix-git__chip')
  await expect(chip).toContainText('main')
  await expect(win.locator('.ix-ctx__tab')).toHaveText(['Terminals', 'Kanban', 'Pull Requests', 'Worktrees', 'Overview'])
  const headerVisible = await win.locator('.ix-ctx__head').evaluate((head) => {
    const parent = head.getBoundingClientRect()
    return [...head.querySelectorAll('.ix-ctx__title, .ix-git__chip, .ix-ctx__tab')].every((node) => {
      const box = node.getBoundingClientRect()
      return box.left >= parent.left && box.right <= parent.right && box.bottom <= innerHeight
    })
  })
  expect(headerVisible).toBe(true)

  git(repo, 'switch', '-c', 'other')
  await expect(chip).toContainText('other', { timeout: 3000 })
  git(repo, 'switch', 'main')
  await expect(chip).toContainText('main', { timeout: 3000 })
  writeFileSync(join(repo, 'tracked'), 'two\n')
  await expect(chip).toContainText('●1', { timeout: 3000 })
  await chip.click()
  await expect(win.getByPlaceholder('Switch branch: type to filter')).toBeFocused()
  await win.getByRole('button', { name: /Commit…/ }).click()
  const dialog = win.getByRole('dialog').filter({ hasText: 'Commit to main' })
  await expect(dialog).toContainText('tracked')
  await dialog.locator('textarea').fill('change tracked')
  await dialog.getByRole('button', { name: 'Commit', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(chip).not.toContainText('●1')
  await expect(chip).toContainText('↑1')
  await chip.click()
  await win.getByRole('button', { name: 'New branch…' }).click()
  await win.getByRole('dialog').filter({ hasText: 'New branch' }).locator('input').fill('feature/e2e')
  await win.getByRole('button', { name: 'Create and switch' }).click()
  await expect(chip).toContainText('feature/e2e')
  await expect(chip).toContainText('no upstream')
  expect(errors).toEqual([])
  await app.close()
  const restarted = await launch(profile, { env: unconfiguredAdo() })
  await restarted.win.locator('.ix-rail__btn--project').click()
  await expect(restarted.win.locator('.ix-git__chip')).toContainText('feature/e2e')
  expect(restarted.errors).toEqual([])
})

test('two bindings keep chips on every tab and the branch filter works by keyboard', async () => {
  const root = tempDir('intersect-project-git-pair-')
  const api = join(root, 'api')
  const web = join(root, 'web')
  for (const repo of [api, web]) {
    git(root, 'init', '-b', 'main', repo)
    git(repo, 'config', 'user.name', 'Test')
    git(repo, 'config', 'user.email', 'test@example.com')
    writeFileSync(join(repo, 'tracked'), 'one\n')
    git(repo, 'add', '-A')
    git(repo, 'commit', '-m', 'initial')
  }
  git(api, 'branch', 'feature/available')
  git(api, 'switch', '-c', 'feature/very-long-branch-name-that-has-to-truncate-before-the-tabs')
  const { app, win, errors } = await launch(userDataDir(), { env: unconfiguredAdo() })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(940, 600))
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize())).toEqual([940, 600])
  const contentSize = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getContentSize())
  await expect.poll(() => win.evaluate(() => [innerWidth, innerHeight])).toEqual(contentSize)
  await openRailSection(win, 'Settings', '.ix-settings')
  await stubFolderPick(app, api)
  await win.getByRole('button', { name: 'Nový projekt (vybrat složku)' }).click()
  await stubFolderPick(app, web)
  await win.getByRole('button', { name: 'Přidat složku' }).click()
  await win.locator('.ix-rail__btn--project').click()
  const chips = win.locator('.ix-git__chip')
  await expect(chips).toHaveCount(2)
  await expect(chips.first()).toContainText('api')
  await expect(chips.last()).toContainText('web')
  await expect(chips.first()).toContainText('feature/very-long')
  for (const tab of ['Terminals', 'Kanban', 'Pull Requests', 'Worktrees', 'Overview']) {
    await win.getByRole('tab', { name: tab }).click()
    await expect(chips).toHaveCount(2)
  }
  await win.getByRole('tab', { name: 'Terminals' }).click()
  const truncate = await chips.first().locator('.ix-git__branch').evaluate((el) => el.scrollWidth > el.clientWidth)
  expect(truncate).toBe(true)
  await chips.first().focus()
  await chips.first().press('Enter')
  const filter = win.getByPlaceholder('Switch branch: type to filter')
  await expect(filter).toBeFocused()
  await expect(win.locator('.ix-git__branch-list button', { hasText: 'feature/available' })).toBeVisible()
  await filter.fill('feature/available')
  await filter.press('ArrowDown')
  await filter.press('Enter')
  await expect(chips.first()).toContainText('feature/available')
  await chips.first().press('Space')
  await filter.fill('feature/prefill')
  await filter.press('Enter')
  await expect(win.getByRole('dialog').locator('input')).toHaveValue('feature/prefill')
  await win.getByRole('dialog').press('Escape')
  await win.locator('.ix-rail__btn--other').click()
  await expect(win.locator('.ix-git__chip')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('failed hook refreshes the staged preview; rejected push closes the commit dialog once', async () => {
  const root = tempDir('intersect-project-git-failures-')
  const repo = join(root, 'repo')
  const origin = join(root, 'origin.git')
  git(root, 'init', '--bare', origin)
  git(root, 'init', '-b', 'main', repo)
  git(repo, 'config', 'user.name', 'Test')
  git(repo, 'config', 'user.email', 'test@example.com')
  writeFileSync(join(repo, 'tracked'), 'one\n')
  git(repo, 'add', '-A')
  git(repo, 'commit', '-m', 'initial')
  git(repo, 'remote', 'add', 'origin', origin)
  git(repo, 'push', '-u', 'origin', 'main')
  const hook = join(repo, '.git', 'hooks', 'pre-commit')
  writeFileSync(hook, '#!/bin/sh\necho hook refused >&2\nexit 1\n', { mode: 0o755 })
  writeFileSync(join(repo, 'new'), 'new\n')
  const { app, win, errors } = await launch(userDataDir(), { env: unconfiguredAdo() })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(940, 600))
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getSize())).toEqual([940, 600])
  const contentSize = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getContentSize())
  await expect.poll(() => win.evaluate(() => [innerWidth, innerHeight])).toEqual(contentSize)
  await openRailSection(win, 'Settings', '.ix-settings')
  await stubFolderPick(app, repo)
  await win.getByRole('button', { name: 'Nový projekt (vybrat složku)' }).click()
  await win.locator('.ix-rail__btn--project').click()
  const chip = win.locator('.ix-git__chip')
  await expect(chip).toContainText('●1')
  await chip.click()
  await win.getByRole('button', { name: /Commit…/ }).click()
  const dialog = win.getByRole('dialog')
  await dialog.locator('textarea').fill('staged after hook')
  await dialog.getByRole('button', { name: 'Commit', exact: true }).click()
  await expect(dialog).toContainText('hook refused')
  await expect(dialog).toContainText('Only the 1 staged files go in')
  await expect(dialog.locator('textarea')).toHaveValue('staged after hook')
  rmSync(hook)
  writeFileSync(join(repo, 'tracked'), 'two\n')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await chip.click()
  await win.getByRole('button', { name: /Commit…/ }).click()
  await expect(dialog).toContainText('1 other changes stay uncommitted')
  await dialog.locator('textarea').fill('only staged')
  await dialog.getByRole('button', { name: 'Commit', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(git(repo, 'show', '--format=', '--name-only', 'HEAD')).toBe('new')
  await expect(chip).toContainText('●1')
  writeFileSync(join(origin, 'hooks', 'pre-receive'), '#!/bin/sh\necho remote refused >&2\nexit 1\n', { mode: 0o755 })
  await chip.click()
  await win.getByRole('button', { name: /Commit…/ }).click()
  await dialog.locator('textarea').fill('commit before failed push')
  await dialog.getByRole('button', { name: 'Commit and push' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(win.locator('.ix-toast').last()).toContainText('Push failed')
  expect(git(repo, 'log', '-1', '--format=%s')).toBe('commit before failed push')
  await expect(chip).toContainText('↑2')
  expect(errors).toEqual([])
})

test('switch warning counts live main-checkout PTYs and excludes a linked worktree', async () => {
  const root = tempDir('intersect-project-git-sessions-')
  const repo = join(root, 'repo')
  git(root, 'init', '-b', 'main', repo)
  git(repo, 'config', 'user.name', 'Test')
  git(repo, 'config', 'user.email', 'test@example.com')
  writeFileSync(join(repo, '.gitignore'), '.claude/\n')
  git(repo, 'add', '-A')
  git(repo, 'commit', '-m', 'initial')
  const linked = join(repo, '.claude', 'worktrees', 'linked')
  git(repo, 'worktree', 'add', '-b', 'feature/linked', linked)
  const { app, win, errors } = await launch(userDataDir(), { env: unconfiguredAdo(), openOther: true })
  await stubQuitConfirm(app)
  await openRailSection(win, 'Settings', '.ix-settings')
  await stubFolderPick(app, repo)
  await win.getByRole('button', { name: 'Nový projekt (vybrat složku)' }).click()
  await win.locator('.ix-rail__btn--project').click()
  await addWorkspace(win, app, repo)
  for (const preset of ['Shell', 'Claude Code']) {
    await win.locator('.ix-iconbtn[title="New terminal"]').click()
    await win.locator('.ix-preset', { hasText: preset }).click()
  }
  await addWorkspace(win, app, linked)
  await win.locator('.ix-iconbtn[title="New terminal"]').click()
  await win.locator('.ix-preset', { hasText: 'Shell' }).click()
  await win.locator('.ix-rail__btn--project').click()
  const chip = win.locator('.ix-git__chip')
  await expect(chip).toContainText('main')
  await chip.click()
  await expect(win.locator('.ix-git__warning')).toContainText('1 Claude session and 1 terminal', { timeout: 3000 })
  expect(errors).toEqual([])
})
